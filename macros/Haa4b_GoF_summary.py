## Script to plot goodness-of-fit (GoF) values from toys

import os
import sys
import numpy as np
import ROOT as R

R.gROOT.SetBatch(True)
import glob
R.gStyle.SetOptStat(0)  ## Don't display stat boxes

USER_IN = False  ## If True, use toy fits generated by user.  If False, use pre-existing inputs.
VERBOSE = False
YEAR    = 'Run2'
DATE    = '2025_09_31'
DMC     = str(sys.argv[1])  ## Data or MC
#CATS    = ['LepHiT','LepLo','gg0lVHi','gg0lVLo','HadXHi','HadXLo']
CATS    = ['VBFjjHiPtHi']
FITS    = ['1x1C']
MIN_TOYS = 90  ## Minimum number of toys the GoF test should contain
MAX_ITOY = 100  ## Maximum toy index to consider (for latest studies)

