    eos_from_config = [eos for eos in (open('config/user.config','r')).readlines() if eos.startswith('EOS_DIR=')]
    loc_from_config = [loc for loc in (open('config/user.config','r')).readlines() if loc.startswith('LOC_DIR=')]
