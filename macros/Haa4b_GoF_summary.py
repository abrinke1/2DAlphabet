    LOC_DIR = loc_from_config[0].replace('LOC_DIR=','').replace('\n','')
    IN_DIR  = EOS_DIR+'/ToyStudies/'+DATE
    #RND_DIR = LOC_DIR+'/output/%s/%stoys/Mergecards/%s%srounded' % (DATE, DMC, DMC, DMC)
